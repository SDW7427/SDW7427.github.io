// Change language function
function changeLanguage(lang) {
    const elements = document.querySelectorAll('[data-i18n]');
    
    elements.forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (translations[lang] && translations[lang][key]) {
            element.innerHTML = translations[lang][key];
        }
    });
    
    // Change page title
    if (translations[lang] && translations[lang]['page-title']) {
        document.title = translations[lang]['page-title'];
    }
    
    // Change favicon
    const favicon = document.getElementById('favicon');
    if (favicon) {
        favicon.href = `images/logo-${lang}.png`;
    }
    
    // Change logo images
    const logoImages = document.querySelectorAll('.logo-header img, .footer-logo img, .footer-logo-small img');
    logoImages.forEach(img => {
        img.src = `images/logo-${lang}.png`;
    });
    
    // Change app store and google play button images
    const appStoreButtons = document.querySelectorAll('.app-btn img[alt*="App Store"], .app-btn img[alt*="앱스토어"], .app-btn img[alt*="Download"]');
    const googlePlayButtons = document.querySelectorAll('.app-btn img[alt*="Google Play"], .app-btn img[alt*="구글"], .app-btn img[alt*="Get it"]');
    
    // Alt text mappings
    const altTexts = {
        appStore: {
            'ja': 'App Storeからダウンロード',
            'ko': 'App Store에서 다운로드 하기',
            'en': 'Download on the App Store'
        },
        googlePlay: {
            'ja': 'Google Playで手に入れよう',
            'ko': 'Google Play 다운로드하기',
            'en': 'Get it on Google Play'
        }
    };
    
    appStoreButtons.forEach(img => {
        img.src = `images/app-store-badge-${lang}.png`;
        img.alt = altTexts.appStore[lang];
    });
    
    googlePlayButtons.forEach(img => {
        img.src = `images/google-play-badge-${lang}.png`;
        img.alt = altTexts.googlePlay[lang];
    });
    
    // Save language preference
    localStorage.setItem('preferred-language', lang);
    
    // Reset and retrigger animations
    resetAndRetriggerAnimations();
}

// Initialize language on page load
function initLanguage() {
    const savedLang = localStorage.getItem('preferred-language') || 'ja';
    changeLanguage(savedLang);
    
    // Update dropdown display
    const languageMap = {
        'ja': '日本語',
        'ko': '한국어',
        'en': 'English'
    };
    
    const currentLanguage = document.querySelector('.current-language');
    if (currentLanguage && languageMap[savedLang]) {
        currentLanguage.textContent = languageMap[savedLang];
    }
    
    // Update dropdown highlighting
    const languageItems = document.querySelectorAll('.language-dropdown li');
    languageItems.forEach(item => {
        const langCode = item.getAttribute('data-lang');
        if (langCode === savedLang) {
            item.style.fontWeight = '700';
            item.style.color = 'var(--primary-color)';
        } else {
            item.style.fontWeight = '400';
            item.style.color = 'var(--text-dark)';
        }
    });
}

// Reset and retrigger animations after language change
function resetAndRetriggerAnimations() {
    // Remove animation class from all animated elements
    const animatedElements = document.querySelectorAll('.fade-in-up');
    animatedElements.forEach(el => {
        el.classList.remove('fade-in-up');
        // Force reflow to restart animation
        void el.offsetWidth;
    });
    
    // Retrigger animations
    if (typeof triggerAnimations === 'function') {
        setTimeout(() => {
            triggerAnimations();
        }, 50);
    }
}

